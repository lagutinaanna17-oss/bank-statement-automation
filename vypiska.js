// Определение статуса операции по правилу светофора
function getStatus(операция) {
  if (операция.есть_документ) {
    return "🟢 зелёный — проводим в 1С";
  } else if (операция.сумма < 10000) {
    return "🟡 жёлтый — мелкая сумма, запросить документ";
  } else {
    return "🔴 красный — нужен бухгалтер";
  }
}

// Банковская выписка — несколько операций
const выписка = [
  { контрагент: "ООО Ромашка", сумма: 15000, есть_документ: true },
  { контрагент: "ИП Иванов", сумма: 5000, есть_документ: false },
  { контрагент: "ООО Стройбаза", сумма: 240000, есть_документ: false },
  { контрагент: "ООО Ромашка", сумма: 8000, есть_документ: true },
];

for (const операция of выписка) {
  const статус = getStatus(операция);
  console.log(операция.контрагент, "|", операция.сумма, "руб |", статус);
}
