// Определение статуса одной операции по правилу светофора
function getStatus(операция) {
  if (операция.есть_документ === true) {
    return "🟢 зелёный — проводим в 1С";
  } else if (операция.есть_документ === false && операция.сумма < 10000) {
    return "🟡 жёлтый — мелкая сумма, запросить документ";
  } else {
    return "🔴 красный — нужен бухгалтер";
  }
}

// Одна банковская операция
const операция = {
  контрагент: "ООО Ромашка",
  сумма: 15000,
  назначение: "Оплата по счету №123 за услуги",
  есть_документ: true
};

const статус = getStatus(операция);

console.log("Контрагент:", операция.контрагент);
console.log("Сумма:", операция.сумма);
console.log("Статус:", статус);
